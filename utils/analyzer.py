def analyze_resume(resume_text, job_role):

    resume_text = resume_text.lower()

    required_skills = JOB_SKILLS.get(job_role, [])

    matched_skills = []
    missing_skills = []

    # Check every required skill
    for skill in required_skills:

        aliases = SKILL_ALIASES.get(skill, [skill])

        skill_found = False

        for alias in aliases:

            if alias in resume_text:
                skill_found = True
                break

        if skill_found:
            matched_skills.append(skill)
        else:
            missing_skills.append(skill)

    # Calculate weighted score
    weights = SKILL_WEIGHTS.get(job_role, {})

    total_weight = 0
    matched_weight = 0

    for skill in required_skills:

        weight = weights.get(skill, 1)

        total_weight += weight

        if skill in matched_skills:
            matched_weight += weight

    if total_weight > 0:

        score = round(
            (matched_weight / total_weight) * 100
        )

    else:

        score = 0

    # Determine readiness level
    if score >= 80:

        readiness = "Job Ready"

        summary = (
            "Excellent match! Your resume contains most of the "
            "important skills required for this role."
        )

    elif score >= 60:

        readiness = "Good Progress"

        summary = (
            "Good progress! You have several relevant skills, "
            "but strengthening the missing skills can improve your profile."
        )

    elif score >= 40:

        readiness = "Beginner"

        summary = (
            "You have started building the required skills. "
            "Focus on the missing skills to become more job-ready."
        )

    else:

        readiness = "Needs Improvement"

        summary = (
            "Your profile needs improvement for this role. "
            "Start by developing the core missing skills."
        )

    # Create recommendations
    recommendations = []

    for skill in missing_skills:

        recommendation = SKILL_RECOMMENDATIONS.get(
            skill,
            f"Learn and practice {skill}."
        )

        recommendations.append({
            "skill": skill,
            "recommendation": recommendation
        })

    # Create interview questions
    interview_questions = []

    for skill in missing_skills:

        questions = INTERVIEW_QUESTIONS.get(
            skill,
            []
        )

        if questions:

            interview_questions.append({
                "skill": skill,
                "questions": questions
            })

    # Create learning roadmaps
    learning_roadmaps = []

    for skill in missing_skills:

        roadmap = LEARNING_ROADMAPS.get(
            skill,
            []
        )

        if roadmap:

            learning_roadmaps.append({
                "skill": skill,
                "steps": roadmap
            })
    matched_count = len(matched_skills)
    missing_count = len(missing_skills)

    # Return analysis result
    return {
        "score": score,
        "readiness": readiness,
        "summary": summary,
        "matched_skills": matched_skills,
        "missing_skills": missing_skills,
        "recommendations": recommendations,
        "interview_questions": interview_questions,
        "learning_roadmaps": learning_roadmaps,
        "resume_text": resume_text,
        "matched_count": matched_count,
        "missing_count": missing_count
    }

def recommend_career(resume_text):

    resume_text = resume_text.lower()

    roles = {
        "software_engineer": [
            "python",
            "java",
            "sql",
            "oops",
            "data structures",
            "algorithms",
            "git"
        ],

        "python_developer": [
            "python",
            "flask",
            "django",
            "sql",
            "rest api",
            "git"
        ],

        "data_analyst": [
            "python",
            "sql",
            "excel",
            "power bi",
            "tableau",
            "pandas",
            "numpy",
            "statistics"
        ]
    }

    role_scores = {}

    for role, skills in roles.items():

        matched = 0

        for skill in skills:

            aliases = SKILL_ALIASES.get(
                skill,
                [skill]
            )

            for alias in aliases:

                if alias in resume_text:

                    matched += 1
                    break

        if skills:

            score = round(
                (matched / len(skills)) * 100
            )

        else:

            score = 0

        role_scores[role] = score

    recommended_role = max(
        role_scores,
        key=role_scores.get
    )

    return {
        "recommended_role": recommended_role,
        "scores": role_scores
    }